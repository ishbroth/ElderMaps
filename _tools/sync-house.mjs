// Copies the house's rules into the server's shared folder (edge functions cannot import from src/):
//   node _tools/sync-house.mjs     ->  supabase/functions/_shared/houseRules.ts
import fs from 'node:fs';
let s = fs.readFileSync('src/lib/house.ts', 'utf8').replace(/\r\n/g, '\n');
s = '// GENERATED by _tools/sync-house.mjs from src/lib/house.ts: do not edit here.\n' + s;
fs.writeFileSync('supabase/functions/_shared/houseRules.ts', s);
console.log('written');
